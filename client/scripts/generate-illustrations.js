#!/usr/bin/env node
/**
 * Embeds the SVG artwork from assets/illustrations (full-colour characters)
 * and assets/glyphs (single-colour, currentColor-tintable UI icons) into
 * constants/illustrations.generated.ts so they can be rendered with SvgXml
 * without a metro transformer.
 *
 * Run from client/:  node scripts/generate-illustrations.js
 */
const fs = require('fs');
const path = require('path');

const ROOT = path.join(__dirname, '..');
const OUT = path.join(ROOT, 'constants', 'illustrations.generated.ts');

function readSvgDir(dir) {
  const abs = path.join(ROOT, dir);
  if (!fs.existsSync(abs)) return [];
  return fs
    .readdirSync(abs)
    .filter((f) => f.endsWith('.svg'))
    .sort()
    .map((f) => {
      const xml = fs.readFileSync(path.join(abs, f), 'utf8').trim();
      const viewBox = xml.match(/viewBox="([\d.\s-]+)"/);
      let width = 100;
      let height = 100;
      if (viewBox) {
        const [, , w, h] = viewBox[1].trim().split(/\s+/).map(Number);
        if (w > 0 && h > 0) {
          width = w;
          height = h;
        }
      }
      return { name: f.replace(/\.svg$/, ''), xml, width, height };
    });
}

function emitRecord(entries) {
  return entries
    .map(
      (e) =>
        `  '${e.name}': { xml: ${JSON.stringify(e.xml)}, width: ${e.width}, height: ${e.height} },`
    )
    .join('\n');
}

const illustrations = readSvgDir('assets/illustrations');
const glyphs = readSvgDir('assets/glyphs');

const banner = `// AUTO-GENERATED by scripts/generate-illustrations.js — do not edit by hand.
// Source SVGs live in assets/illustrations/ and assets/glyphs/.

export interface SvgAsset {
  xml: string;
  width: number;
  height: number;
}
`;

const body = `
export const ILLUSTRATIONS = {
${emitRecord(illustrations)}
} as const satisfies Record<string, SvgAsset>;

export const GLYPHS = {
${emitRecord(glyphs)}
} as const satisfies Record<string, SvgAsset>;
`;

fs.writeFileSync(OUT, banner + body);
console.log(
  `Wrote ${path.relative(ROOT, OUT)}: ${illustrations.length} illustrations, ${glyphs.length} glyphs`
);
